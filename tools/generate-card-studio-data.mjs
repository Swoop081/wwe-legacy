import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { collectionCards } from "../js/data/collection.js";
import { superstars } from "../js/data/superstars.js";
import { decks } from "../js/data/decks.js";
import { sets } from "../js/data/sets.js";
import { MERCH_ITEMS } from "../js/data/merch.js";
import { SUPERSTAR_VARIANTS } from "../js/data/superstar-variants.js";
import { artworkFor, canonicalImageKeyForCard, canonicalCardImagePath, canonicalBasePlatePath } from "../js/data/artwork.js";
import { fixedPrintingTierFor } from "../js/data/variants.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const starList = Object.values(superstars);
const starRank = Object.fromEntries(starList.map((star, index) => [star.id, index]));
const usage = new Map();

for (const [superstarId, deck] of Object.entries(decks)) {
  for (const card of deck ?? []) {
    if (!card?.id) continue;
    if (!usage.has(card.id)) usage.set(card.id, new Set());
    usage.get(card.id).add(superstarId);
  }
}
for (const star of starList) {
  for (const id of [`superstar-${star.id}`, star.entranceId, star.specialId].filter(Boolean)) {
    if (!usage.has(id)) usage.set(id, new Set());
    usage.get(id).add(star.id);
  }
}

const sortStars = ids => [...ids].sort((a, b) => (starRank[a] ?? 999) - (starRank[b] ?? 999) || a.localeCompare(b));
const relativeArt = card => {
  const value = artworkFor(card);
  return value ? String(value).replace(/^\.\//, "").split("?")[0] : null;
};
const relationData = card => {
  const specific = new Set([
    ...(card.superstarId ? [card.superstarId] : []),
    ...(card.allowedSuperstarIds ?? []),
  ]);
  const deck = usage.get(card.id) ?? new Set();
  return {
    specificSuperstarIds: sortStars(specific),
    deckSuperstarIds: sortStars(deck),
    librarySuperstarIds: sortStars(new Set([...specific, ...deck])),
  };
};
const studioShape = (card, source="collector") => ({
  id: card.id,
  name: card.name,
  kind: card.kind,
  source,
  setId: card.setId ?? null,
  cardNumber: card.cardNumber ?? null,
  cardCode: card.cardCode ?? (source === "merch" ? "MERCH" : source === "variant" ? "VARIANT" : "—"),
  superstarId: card.superstarId ?? null,
  ...relationData(card),
  universalSuperstarCard: card.id === "entrance-amazing",
  imageKey: canonicalImageKeyForCard(card),
  artKey: canonicalImageKeyForCard(card),
  currentArt: relativeArt(card),
  finishedPath: canonicalCardImagePath(card),
  basePlatePath: canonicalBasePlatePath(card),
  cost: card.cost ?? null,
  damage: card.damage ?? null,
  amount: card.amount ?? null,
  method: card.method ?? null,
  moveType: card.moveType ?? null,
  counterState: card.counterState ?? null,
  counterStates: card.counterStates ?? null,
  submissionTarget: card.submissionTarget ?? null,
  counterSubmissionTargets: card.counterSubmissionTargets ?? null,
  rarity: card.rarity ?? 1,
  fixedPrintingTier: fixedPrintingTierFor(card) ?? null,
  requirements: card.requirements ?? null,
  rulesText: card.rulesText ?? card.effectText ?? null,
  duration: card.duration ?? null,
  scope: card.scope ?? null,
  variantType: card.variantType ?? null,
  hpBonus: card.hpBonus ?? null,
  ultraRare: !!card.ultraRare,
  finisher: !!card.finisher,
  signature: !!card.signature,
  trademark: !!card.trademark,
});

const studioCards = [
  ...collectionCards.map(card => studioShape(card, "collector")),
  ...MERCH_ITEMS.map(card => studioShape(card, "merch")),
  ...SUPERSTAR_VARIANTS.map(card => studioShape(card, "variant")),
];
const studioSuperstars = starList.map(star => ({ id: star.id, name: star.name, setId: star.setId }));
const studioSets = Object.values(sets).map(set => ({
  id: set.id,
  name: set.name,
  displayName: set.displayName ?? set.name,
  developmentOnly: !!set.developmentOnly,
  type: set.type ?? null,
}));
const output = `// AUTO-GENERATED by tools/generate-card-studio-data.mjs.\n// Includes collector cards, Merch and Superstar Variants.\n// Card codes are inherited from the canonical manifests/data sources.\nconst STUDIO_CARDS = ${JSON.stringify(studioCards)};\nconst STUDIO_SUPERSTARS = ${JSON.stringify(studioSuperstars)};\nconst STUDIO_SETS = ${JSON.stringify(studioSets)};\n`;
fs.writeFileSync(path.join(root, "js/tools/card-art-studio-data.js"), output);
console.log(JSON.stringify({
  cards: studioCards.length,
  collectorCards: collectionCards.length,
  merch: MERCH_ITEMS.length,
  variants: SUPERSTAR_VARIANTS.length,
  superstars: studioSuperstars.length,
  sets: studioSets.length,
}, null, 2));
